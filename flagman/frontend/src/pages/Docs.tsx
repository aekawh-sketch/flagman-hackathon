function count(groups: Group[]) {
  const items = groups.flatMap((g) => g.items);
  return { done: items.filter((i) => i.status === "done").length, total: items.length };
}

function scrollTo(id: string) {
  document.getElementById(id)?.scrollIntoView({ behavior: "smooth", block: "start" });
}

function WhereLinks({ where }: { where: Where[] }) {
  const { loc } = useSession();
  return (
    <HStack gap="1.5" wrap="wrap" mt="2">
      {where.map((w) => w.href ? (
        <Button key={w.label} asChild size="2xs" variant="outline">
          <a href={w.href} target="_blank" rel="noreferrer">{w.label} <LuExternalLink /></a>
        </Button>
      ) : (
        <Button key={w.label} asChild size="2xs" variant="outline">
          <Link to={`/${loc}/${w.to}`}>{w.label} <LuArrowRight /></Link>
        </Button>
      ))}
    </HStack>
  );
}

function ItemRow({ item }: { item: Item }) {
  const st = item.status && STATUS_BADGE[item.status];
  return (
    <Box py="3" borderTopWidth="1px" borderColor="border.muted" _first={{ borderTopWidth: 0, pt: 0 }}>
      {/* На телефоне код и статус — строкой над названием: иначе название зажато между плашками. */}
      <Flex gap="2" align="start" wrap={{ base: "wrap", sm: "nowrap" }}>
        {item.code && <Badge variant="outline" flexShrink={0} mt="0.5" fontVariantNumeric="tabular-nums">{item.code}</Badge>}
        <Text fontWeight="medium" flex="1" minW={{ base: "full", sm: "0" }} order={{ base: 3, sm: 0 }}>{glue(item.title)}</Text>
        {st && <Badge colorPalette={st.palette} variant="subtle" flexShrink={0} mt="0.5" ml={{ base: "auto", sm: "0" }}>{st.label}</Badge>}
      </Flex>
      <Text textStyle="sm" color="fg.muted" mt="1">{glue(item.how)}</Text>
      {item.points && (
        <List.Root as="ul" textStyle="sm" color="fg.muted" mt="1.5" ps="4" gap="1">
          {item.points.map((p) => <List.Item key={p}>{glue(p)}</List.Item>)}
        </List.Root>
      )}
      {item.where && <WhereLinks where={item.where} />}
    </Box>
  );
}

function GroupCard({ group, badge }: { group: Group; badge?: { label: string; palette: string } }) {
  return (
    <Section id={group.id} scrollMarginTop="80px" title={
      <HStack as="span" gap="2" wrap="wrap">
        <span>{group.title}</span>
        {group.source && <Badge variant="subtle">PDF, {group.source}</Badge>}
        {badge && <Badge colorPalette={badge.palette} variant="subtle">{badge.label}</Badge>}
      </HStack>}>
      <Stack gap="0">{group.items.map((i) => <ItemRow key={(i.code ?? "") + i.title} item={i} />)}</Stack>
    </Section>
  );
}

