/** URL фото для позиции/ключа */
export function photoUrl(key, w = 640, h = 480) {
  const p = PHOTOS[key] || PHOTOS.default;
  if (p.startsWith('photos/') || p.startsWith('data:') || p.startsWith('http')) return p;
  return `https://images.unsplash.com/${p}?w=${w}&h=${h}&fit=crop&crop=entropy&q=75&auto=format`;
}
